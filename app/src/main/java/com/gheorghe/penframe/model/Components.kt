enum class PropType { TEXT, BOOL, CHOICE, NUMBER, ICON }

/** An editable property shown in the inspector for a component instance. */
data class PropSpec(
    val key: String,
    val label: String,
    val type: PropType,
    val choices: List<String> = emptyList(),
    val range: ClosedFloatingPointRange<Float> = 0f..100f,
)

private fun text(key: String, label: String) = PropSpec(key, label, PropType.TEXT)
private fun bool(key: String, label: String) = PropSpec(key, label, PropType.BOOL)
private fun choice(key: String, label: String, vararg values: String) = PropSpec(key, label, PropType.CHOICE, values.toList())
private fun number(key: String, label: String, range: ClosedFloatingPointRange<Float> = 0f..100f) =
    PropSpec(key, label, PropType.NUMBER, range = range)
private fun icon(key: String = "icon", label: String = "Icon") = PropSpec(key, label, PropType.ICON)

private val ENABLED = bool("enabled", "Enabled")

